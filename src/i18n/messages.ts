export type MessageKey = keyof MessageParams;

/** Explicit-locale whole-message interpolation. Caller renders the result as text. */
export function t<K extends MessageKey>(locale: AppLocale, key: K,
  ...args: MessageParams[K] extends undefined ? [] : [params: MessageParams[K]]
): string {
  const values = args[0] as Record<string, string | number> | undefined;
  return (locale === "de" ? de : en)[key].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    values && Object.hasOwn(values, name) ? String(values[name]) : placeholder);
}
